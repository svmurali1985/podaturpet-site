"""Build the homepage cascade without dependencies or changing shared page assets."""
from pathlib import Path
import json
R=Path(__file__).resolve().parents[1]
files=json.loads((R/'content/home-styles.json').read_text())
parts=['/* Generated by tools/build_home_styles.py. Edit source CSS, then rebuild. */']
for name in files:
 p=(R/name).resolve()
 if p.parent!=R or p.suffix!='.css':raise ValueError('Only root CSS sources are permitted')
 parts.append('/* Source: '+name+' */\n'+p.read_text())
(R/'podaturpet-homepage.css').write_text('\n'.join(parts)+'\n')
print('Homepage stylesheet built from',len(files),'sources')
